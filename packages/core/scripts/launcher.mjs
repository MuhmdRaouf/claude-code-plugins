// The launcher every provider plugin ships as plugin/dist/run: Claude Code's hooks, commands and agents start a bundle
// with `sh "${CLAUDE_PLUGIN_ROOT}/dist/run" <bundle>.js [args...]`. It runs the bundle on Bun (the default) when bun
// is on PATH or in Bun's own install dir, else on Node (the fallback). The bundles run unchanged on both; everything
// they start themselves (router, workers, drivers) reuses the runtime they run on.

/** The launcher script for the plugin `name` (zai, kimi, ...). */
export function launcherScript(name) {
  return `#!/bin/sh
# ${name}: starts one of this plugin's bundles on Bun (the default) or Node (the fallback).
#   sh "\${CLAUDE_PLUGIN_ROOT}/dist/run" <bundle>.js [args...]
# Bun is taken from PATH, else from Bun's install dir (a Claude Code started from a GUI may not have it on PATH).
# With neither runtime it says so on stderr and exits 127; a hook (any --hook argument) exits 0 silently instead,
# since a hook never blocks or fails Claude Code. Generated by the plugin's scripts/build.mjs; do not edit.
dir=$(dirname -- "$0")
bundle=$1
shift
runtime=$(command -v bun 2>/dev/null)
installed="\${BUN_INSTALL:-$HOME/.bun}/bin/bun"
[ -n "$runtime" ] || { [ -x "$installed" ] && runtime=$installed; }
[ -n "$runtime" ] || runtime=$(command -v node 2>/dev/null)
if [ -n "$runtime" ]; then
  exec "$runtime" "$dir/$bundle" "$@"
fi
for arg in "$@"; do
  [ "$arg" = "--hook" ] && exit 0
done
echo "${name}: needs Bun 1.3 or newer (or Node 22 or newer) on PATH" >&2
exit 127
`;
}

/** plugin/dist/package.json: declares the ESM bundles beside it as modules, so Node runs them as such whatever
 *  package.json sits above the plugin's install dir (a `~/package.json`, one with `"type": "commonjs"`) and without
 *  relying on syntax detection, which Node 22 before 22.7 does not have. Bun needs none of this but ignores it. */
export const distPackageJson = `${JSON.stringify({ private: true, type: "module" }, null, 2)}\n`;
